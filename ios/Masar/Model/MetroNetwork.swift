import Foundation
import Observation
import CoreLocation

struct Station: Codable, Identifiable, Hashable {
    let id: String
    let ar: String
    let en: String
    let alias: String
    let x: Double   // schematic map position, 0…1000
    let y: Double   // schematic map position, 0…980
    let lat: Double?
    let lng: Double?
    /// "official" (RCRC open data), "ref" (published point), "est" (estimated, 0.2–1 km)
    let geo: String?

    var dataCoordinate: CLLocationCoordinate2D? {
        guard let lat, let lng else { return nil }
        return CLLocationCoordinate2D(latitude: lat, longitude: lng)
    }
}

struct MetroLine: Codable, Identifiable, Hashable {
    let id: Int
    let key: String
    let nameEn: String
    let axisAr: String
    let lengthKm: Double
    let speedKmh: Double
    let colorLight: String
    let colorDark: String
    let stations: [String]
}

struct NetworkParams: Codable, Hashable {
    let dwellMin: Double
    let transferMin: Double
    let initialWaitMin: Double
}

struct NetworkFile: Codable {
    let version: Int
    let params: NetworkParams
    let stations: [Station]
    let lines: [MetroLine]
}

/// The metro graph, loaded once from `network.json` (generated by tools/build.py).
@Observable
final class MetroNetwork {
    let params: NetworkParams
    let stations: [Station]
    let lines: [MetroLine]
    let stationByID: [String: Station]
    let lineByID: [Int: MetroLine]
    /// Lines serving each station, in line order.
    let linesAt: [String: [Int]]
    /// Estimated minutes between consecutive stations on each line.
    let hopMinutes: [Int: Double]
    /// Normalized Arabic + English + aliases, for search.
    let searchKey: [String: String]

    init(file: NetworkFile) {
        params = file.params
        stations = file.stations
        lines = file.lines
        stationByID = Dictionary(uniqueKeysWithValues: file.stations.map { ($0.id, $0) })
        lineByID = Dictionary(uniqueKeysWithValues: file.lines.map { ($0.id, $0) })
        var at: [String: [Int]] = [:]
        for line in file.lines { for s in line.stations { at[s, default: []].append(line.id) } }
        linesAt = at
        var hop: [Int: Double] = [:]
        for line in file.lines {
            let spacing = line.lengthKm / Double(max(1, line.stations.count - 1))
            hop[line.id] = spacing / line.speedKmh * 60 + file.params.dwellMin
        }
        hopMinutes = hop
        searchKey = Dictionary(uniqueKeysWithValues: file.stations.map {
            ($0.id, StationSearch.normalize("\($0.ar) \($0.en) \($0.alias)"))
        })
    }

    static func load(bundle: Bundle = .main) -> MetroNetwork {
        guard let url = bundle.url(forResource: "network", withExtension: "json"),
              let data = try? Data(contentsOf: url),
              let file = try? JSONDecoder().decode(NetworkFile.self, from: data) else {
            fatalError("network.json is missing from the app bundle or invalid. Run tools/build.py.")
        }
        return MetroNetwork(file: file)
    }

    func isInterchange(_ id: String) -> Bool { (linesAt[id]?.count ?? 0) > 1 }

    // MARK: geography

    /// Positions confirmed on Apple Maps at run time (see StationRefiner); they win over estimates.
    private(set) var refined: [String: CLLocationCoordinate2D] = MetroNetwork.loadRefined()

    func coordinate(of id: String) -> CLLocationCoordinate2D? {
        refined[id] ?? stationByID[id]?.dataCoordinate
    }

    /// True when a station's position is still an estimate.
    func isApproximate(_ id: String) -> Bool {
        refined[id] == nil && !["official", "ref"].contains(stationByID[id]?.geo ?? "")
    }

    var hasApproximatePositions: Bool { stations.contains { isApproximate($0.id) } }

    func nearest(to location: CLLocation, count: Int = 3) -> [NearbyStation] {
        stations.compactMap { st -> NearbyStation? in
            guard let c = coordinate(of: st.id) else { return nil }
            let d = location.distance(from: CLLocation(latitude: c.latitude, longitude: c.longitude))
            return NearbyStation(station: st, meters: d, approximate: isApproximate(st.id))
        }
        .sorted { $0.meters < $1.meters }
        .prefix(count)
        .map { $0 }
    }

    func setRefined(_ id: String, _ c: CLLocationCoordinate2D) {
        refined[id] = c
        let dict = refined.mapValues { [$0.latitude, $0.longitude] }
        UserDefaults.standard.set(dict, forKey: Self.refinedKey)
    }

    private static let refinedKey = "geo.refined.v1"
    private static func loadRefined() -> [String: CLLocationCoordinate2D] {
        let raw = UserDefaults.standard.dictionary(forKey: refinedKey) as? [String: [Double]] ?? [:]
        return raw.compactMapValues { $0.count == 2 ? CLLocationCoordinate2D(latitude: $0[0], longitude: $0[1]) : nil }
    }
}

struct NearbyStation: Identifiable, Hashable {
    let station: Station
    let meters: Double
    let approximate: Bool
    var id: String { station.id }
    /// Street walking is ~25% longer than the straight line; 80 m per minute.
    var walkMinutes: Double { meters * 1.25 / 80 }
}

enum StationSearch {
    static func normalize(_ s: String) -> String {
        var r = s.lowercased()
        r = r.replacingOccurrences(of: "[\\u064B-\\u0652\\u0640]", with: "", options: .regularExpression)
        r = r.replacingOccurrences(of: "[أإآ]", with: "ا", options: .regularExpression)
        r = r.replacingOccurrences(of: "ة", with: "ه").replacingOccurrences(of: "ى", with: "ي")
        r = r.folding(options: [.diacriticInsensitive], locale: nil)
        r = r.replacingOccurrences(of: "[^\\p{L}\\p{N}]+", with: " ", options: .regularExpression)
        return r.trimmingCharacters(in: .whitespaces)
    }

    static func filter(_ query: String, in network: MetroNetwork) -> [Station] {
        let tokens = normalize(query).split(separator: " ").map(String.init)
        let sorted = network.stations.sorted {
            L10n.stationName($0).localizedStandardCompare(L10n.stationName($1)) == .orderedAscending
        }
        guard !tokens.isEmpty else { return sorted }
        return sorted.filter { st in
            let key = network.searchKey[st.id] ?? ""
            return tokens.allSatisfy { key.contains($0) }
        }
    }
}
